"""Cohen's kappa between two completed adjudication worksheets (#37).

    python scripts/score_adjudication.py                      # all worksheets found
    python scripts/score_adjudication.py --pair deepti varun

Writes `reports/adjudication_kappa.md`. Refuses a partly filled worksheet:
agreement on the finished half of a sheet is not agreement on the sheet.

Agreement between the two humans and agreement with the machine draft are
reported in separate sections on purpose. The first is the reliability of the
annotation; the second is how good the draft was. Reading the second as the
first is how a persuasive draft gets mistaken for two people agreeing.
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
from datetime import date
from pathlib import Path

from eval.adjudication import against_draft, build_items, load_worksheet, score
from eval.gold import load_gold_graph

REPO = Path(__file__).resolve().parent.parent
QUERIES = REPO / "data/eval/queries_dev.jsonl"
SHEETS = REPO / "data/eval/gold/dev/adjudication"
REPORT = REPO / "reports/adjudication_kappa.md"

#: Below this, the annotation guide needs work before the labels are usable.
USABLE_KAPPA = 0.6


def _query_ids() -> list[str]:
    return [
        json.loads(line)["query_id"]
        for line in QUERIES.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def _fmt(value: float | None, places: int = 3) -> str:
    return "n/a" if value is None else f"{value:.{places}f}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pair", nargs=2, metavar=("A", "B"), help="annotator slugs")
    parser.add_argument("--sheets", type=Path, default=SHEETS, help="worksheet directory")
    parser.add_argument("--report", type=Path, default=REPORT, help="where to write")
    args = parser.parse_args(argv)

    found = sorted(args.sheets.glob("worksheet-*.csv"))
    if len(found) < 2:
        print(
            f"need at least two worksheets in {args.sheets}; found {len(found)}.\n"
            "Run scripts/prepare_adjudication.py first.",
            file=sys.stderr,
        )
        return 2

    if args.pair:
        wanted = {f"worksheet-{name.strip().lower()}.csv" for name in args.pair}
        found = [path for path in found if path.name in wanted]
        if len(found) != 2:
            print(f"could not find both of {args.pair}", file=sys.stderr)
            return 2

    graphs = {q: load_gold_graph(q) for q in _query_ids()}
    items = build_items(graphs)

    loaded = {}
    for path in found:
        name = path.stem.removeprefix("worksheet-")
        try:
            loaded[name] = load_worksheet(path)
        except ValueError as exc:
            print(f"  {path.name}: {exc}", file=sys.stderr)
            return 1

    lines = [
        "# Annotator agreement on the dev gold graphs (#37)",
        "",
        "<!-- Generated by scripts/score_adjudication.py. Do not edit by hand. -->",
        "",
        f"Run {date.today()}. Worksheets: {', '.join(sorted(loaded))}.",
        "",
        "Each annotator labelled **every** gold edge independently, from a sheet carrying",
        "the span and the two variables and no label. Agreement with the machine draft is",
        "a separate section below and is **not** an agreement measurement.",
        "",
    ]

    worst: list[float] = []
    spans: list[float] = []
    for left, right in itertools.combinations(sorted(loaded), 2):
        lines += [f"## {left} vs {right}", ""]
        try:
            dimensions = score(loaded[left], loaded[right])
        except ValueError as exc:
            lines += [f"**Cannot score:** {exc}", ""]
            continue
        lines += [
            "| dimension | items | raw agreement | chance | kappa | 95% interval |",
            "|---|---:|---:|---:|---:|---|",
        ]
        for row in dimensions:
            interval = f"{row.ci95[0]:.3f} to {row.ci95[1]:.3f}" if row.ci95 is not None else "n/a"
            lines.append(
                f"| {row.dimension} | {row.items} | {_fmt(row.observed_agreement)} | "
                f"{_fmt(row.chance_agreement)} | **{_fmt(row.kappa)}** | {interval} |"
            )
            if row.kappa is not None:
                worst.append(row.kappa)
            if row.ci95 is not None:
                spans.append(row.ci95[1] - row.ci95[0])
        lines.append("")
        for row in dimensions:
            if row.note:
                lines += [f"- **{row.dimension}.** {row.note}", ""]
            if row.paradox_warning:
                lines += [
                    f"- **{row.dimension}: high raw agreement with a low kappa.** One label"
                    " dominates, so chance agreement is close to the observed agreement and"
                    " kappa collapses. The annotators did agree on nearly every item. Quote"
                    f" the raw agreement ({_fmt(row.observed_agreement)}) next to the kappa,"
                    " never the kappa alone.",
                    "",
                ]
            if row.kappa is None and row.items:
                lines += [
                    f"- **{row.dimension}: kappa undefined.** Both annotators used a single"
                    " label throughout, so chance agreement is 1. That is a property of the"
                    " sample, not a failure to agree.",
                    "",
                ]

    widest = max(spans) if spans else None

    lines += [
        "## Against the machine draft",
        "",
        "Not agreement. This is how good the draft was.",
        "",
    ]
    lines += [
        "| annotator | edges kept | direction matches draft | strength matches draft | edges dropped |",
        "|---|---:|---:|---:|---:|",
    ]
    for name in sorted(loaded):
        stats = against_draft(loaded[name], items, graphs)
        lines.append(
            f"| {name} | {stats['items']} | {_fmt(stats['direction_match'])} | "
            f"{_fmt(stats['strength_match'])} | {_fmt(stats['dropped'])} |"
        )
    lines += [
        "",
        "A low strength-match figure is the expected outcome, not an error: the draft set"
        " strength from cue words and the annotator reads the sentence.",
        "",
        "## Reading this",
        "",
        f"The dev gold set is {len(items)} edges, a small sample for a kappa."
        + (
            f" The widest 95% interval in this run spans **{widest:.2f}** on a scale that"
            " only runs from -1 to 1, so quote the interval rather than the point estimate"
            " and do not set these figures beside published kappas from thousand-item"
            " corpora."
            if widest is not None
            else ""
        ),
        "",
        f"The pre-declared threshold for usable labels is **kappa ≥ {USABLE_KAPPA}** on the"
        " `asserts` and `direction` dimensions. Below that the annotation guide needs work"
        " before the labels are used, and `strength` falls back to the declared"
        " direct-vs-hedged collapse (`eval.agreement.strength_agreement`).",
        "",
    ]

    if worst:
        floor = min(worst)
        lines += [
            f"Lowest kappa in this run: **{floor:.3f}** "
            f"({'at or above' if floor >= USABLE_KAPPA else 'below'} the {USABLE_KAPPA} threshold).",
            "",
        ]

    args.report.write_text(
        "\n".join(line.rstrip() for line in lines).rstrip() + "\n", encoding="utf-8"
    )
    print(f"wrote {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
