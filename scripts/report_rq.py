"""Write the RQ1 and RQ2 findings from a reviewed evaluation (#43, #44).

    python scripts/report_rq.py --review-dir data/interim/support-review \
        --references data/eval/gold/dev

Runs today. With no reviewed results it writes nothing, names the exact
precondition that is missing and exits 2 - so the gap stays visible instead of
becoming an empty section in the report.

Both findings carry the pre-declared gates from `eval.rq`: a hop bucket below
the established-edge minimum cannot support a claim about that hop, a trend
needs three usable buckets, and four queries is below the threshold for any
inferential claim. Those numbers are fixed in the module, not chosen here, so
they cannot be picked after seeing which side of them the data lands on.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

from eval.review import evaluate
from eval.rq import (
    BUCKETS,
    MIN_ESTABLISHED_PER_BUCKET,
    MIN_QUERIES_FOR_INFERENCE,
    Rq1Finding,
    rq1_finding,
    rq2_finding,
)
from eval.stats import exploratory_contrasts

REPO = Path(__file__).resolve().parent.parent
RQ1 = REPO / "reports/rq1_hop_decay.md"
RQ2 = REPO / "reports/rq2_verification.md"

GENERATED = "<!-- Generated by scripts/report_rq.py. Do not edit by hand. -->"


def _fmt(value: float | None, places: int = 3) -> str:
    return "n/a" if value is None else f"{value:.{places}f}"


def _interval(finding) -> str:
    if finding.uer_ci95 is None:
        return "n/a - needs at least 2 paired queries" if finding.queries < 2 else "n/a"
    return f"{finding.uer_ci95[0]:.3f} to {finding.uer_ci95[1]:.3f}"


def _rq1_section(finding: Rq1Finding) -> list[str]:
    lines = [
        f"## {finding.condition}",
        "",
        finding.statement,
        "",
        "| hop | UER | strength inflation | reference recall | established edges | "
        "queries with denominator | usable for a claim |",
        "|---|---:|---:|---:|---:|---:|---|",
    ]
    for row in finding.buckets:
        usable = "yes" if row.usable else f"**no** - {row.reason}"
        lines.append(
            f"| {row.bucket} | {_fmt(row.uer)} | {_fmt(row.strength_inflation)} | "
            f"{_fmt(row.reference_edge_recall)} | {row.established_edges} | "
            f"{row.queries_with_denominator} | {usable} |"
        )
    lines.append("")
    if finding.deep_bucket_empty:
        lines += [
            "**The hop 3-or-deeper bucket is empty.** This is the slice H1 is about, so its "
            "absence is the finding, not a footnote. It traces to D-18: the September bond "
            "sell-off was dropped because `gsec_10y_pct.csv` ends 31 August and never reaches "
            "7%, and that was the only anchor carrying a yield chain deep enough to produce "
            "hop-3 edges.",
            "",
        ]
    return lines


def _secondary_section(result: dict) -> list[str]:
    """Provenance accuracy and strict path validity (#60).

    Both are proposal secondary metrics that `eval.metrics` has always computed
    and nothing ever printed. Provenance accuracy is the one that checks the
    verifier's own labelling, which is the mechanism the study rests on, so a
    UER table without it leaves the instrument unmeasured.
    """
    aggregate = result.get("aggregate") or {}
    if not aggregate:
        return []
    lines = [
        "## Secondary metrics",
        "",
        "| condition | provenance accuracy | strict path validity |",
        "|---|---:|---:|",
    ]
    for condition in sorted(aggregate):
        overall = (aggregate[condition] or {}).get("overall") or {}
        lines.append(
            f"| {condition} | {_fmt_mean(overall.get('provenance_accuracy'))} | "
            f"{_fmt_mean(overall.get('strict_path_validity'))} |"
        )
    lines += [
        "",
        "Higher is better for both. `n/a` is a missing denominator, not a zero: a "
        "condition that produced no path cannot have an invalid one.",
        "",
    ]
    return lines


def _fmt_mean(value) -> str:
    if isinstance(value, dict):
        value = value.get("mean")
    return "n/a" if value is None else f"{value:.3f}"


def _exploratory_section(result: dict) -> list[str]:
    """M against B2 and the two ablations (#59, H2c).

    Reported under its own heading and labelled exploratory, because the
    proposal declares exactly two tests and these are not among them.
    """
    scores = result.get("per_query") or {}
    if "M" not in scores:
        return []
    lines = [
        "## Exploratory: M against the prompting control and the ablations",
        "",
        "**Not pre-declared.** The proposal declares two tests - B1 deep-minus-shallow "
        "for RQ1 and M-minus-B1 for RQ2. Everything in this section is exploratory by "
        "its own statistics section and must not be promoted to a result.",
        "",
        "| contrast | tests | UER | 95% interval | pairs | strength inflation |",
        "|---|---|---:|---|---:|---:|",
    ]
    purpose = {
        "M_minus_B2_overall": "H2c: beats prompted self-labelling",
        "M_minus_A-NoVerify_overall": "does verification help?",
        "M_minus_A-NoLoop_overall": "does targeted retrieval help?",
    }
    uer = exploratory_contrasts(scores, metric="uer")
    inflation = exploratory_contrasts(scores, metric="strength_inflation")
    for key, why in purpose.items():
        row = uer.get(key)
        if not row:
            continue
        interval = row.get("ci95")
        lines.append(
            f"| `{key.replace('_overall', '')}` | {why} | {_fmt(row.get('estimate'))} | "
            f"{(f'{interval[0]:+.3f} to {interval[1]:+.3f}' if interval else 'n/a')} | "
            f"{row.get('paired_queries', 0)} | "
            f"{_fmt((inflation.get(key) or {}).get('estimate'))} |"
        )
    lines += [
        "",
        "Negative UER favours M. **Read the pair count before the estimate**: a contrast "
        "resting on one query is the same number repeated, and its interval is zero-width "
        "for that reason rather than from precision.",
        "",
    ]
    return lines


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--review-dir", type=Path)
    source.add_argument(
        "--scores",
        type=Path,
        help=(
            "a scored result JSON written earlier by eval.review, instead of "
            "re-evaluating. The review packets carry corpus text and are gitignored, so "
            "only the machine that ran the sweep can use --review-dir; the scored JSON "
            "is committed, which lets anyone regenerate these reports from it."
        ),
    )
    parser.add_argument("--references", type=Path, default=REPO / "data/eval/gold/dev")
    parser.add_argument(
        "--no-references",
        action="store_true",
        help=(
            "score without the reference graphs. RQ1 does not need them - UER is "
            "measured over generated edges - but it disables reference-edge recall, so "
            "the H2d guard goes undetermined and RQ2 cannot report a repair."
        ),
    )
    parser.add_argument("--corpus", type=Path, default=REPO / "data/processed/articles.jsonl")
    parser.add_argument("--rq1", type=Path, default=RQ1)
    parser.add_argument("--rq2", type=Path, default=RQ2)
    args = parser.parse_args(argv)

    try:
        if args.scores:
            result = json.loads(args.scores.read_text(encoding="utf-8"))
        else:
            result = evaluate(
                review_dir=args.review_dir,
                reference_dir=None if args.no_references else args.references,
                corpus=args.corpus,
            )
    except FileNotFoundError as exc:
        print(f"missing input: {exc}", file=sys.stderr)
        print(
            "\nRQ1 and RQ2 need, in order:\n"
            "  1. a dev sweep on the v7 corpus            (#41, needs the pinned model)\n"
            "  2. blind support judgements on its edges   (#42, needs a human)\n"
            "  3. a signed reference review receipt       (#37, needs two humans)\n"
            "Nothing was written.",
            file=sys.stderr,
        )
        return 2
    except ValueError as exc:
        print(f"preconditions not met: {exc}", file=sys.stderr)
        print("Nothing was written.", file=sys.stderr)
        return 2

    scores = result["per_query"]
    stamp = [
        f"Run {date.today()}.",
        f"Reviewer **{result['reviewer']}**, reviewed {result['reviewed_on']}.",
        f"Judgements `{result['judgments_sha256'][:12]}`, reference receipt "
        f"`{(result['reference_review_receipt_sha256'] or 'none')[:12]}`.",
        "",
        f"Status: {result['status']}.",
        "",
    ]

    rq1 = [
        "# RQ1 - does grounding decay with hop distance?",
        "",
        GENERATED,
        "",
        *stamp,
        "H1: the share of established edges with no supporting source rises with distance "
        "from the anchor. Measured as UER, macro-averaged over queries, sliced by hop 1 / 2 / "
        "3-or-deeper.",
        "",
        f"Pre-declared gates: a bucket needs **{MIN_ESTABLISHED_PER_BUCKET} established "
        f"edges** to support a claim about that hop, a monotone trend needs **all "
        f"{len(BUCKETS)} buckets** usable, and an inferential claim needs "
        f"**{MIN_QUERIES_FOR_INFERENCE} queries**.",
        "",
    ]
    for condition in sorted(scores):
        rq1 += _rq1_section(
            rq1_finding(condition, result["aggregate"][condition], scores[condition])
        )
    args.rq1.write_text("\n".join(line.rstrip() for line in rq1).rstrip() + "\n", encoding="utf-8")

    finding = rq2_finding(result)
    guard = result.get("recall_guard") or {}
    rq2 = [
        "# RQ2 - do verification and targeted retrieval repair it?",
        "",
        GENERATED,
        "",
        *stamp,
        finding.statement,
        "",
        "| quantity | M minus B1 |",
        "|---|---:|",
        f"| UER (negative is better) | {_fmt(finding.uer_delta)} |",
        f"| UER 95% interval | {_interval(finding)} |",
        f"| strength inflation | {_fmt(finding.strength_inflation_delta)} |",
        f"| reference-edge recall (H2d) | {_fmt(finding.recall_delta)} |",
        f"| H2d floor | {finding.recall_guard_minimum:+.2f} |",
        f"| H2d verdict | **{finding.recall_guard}** |",
        f"| paired queries with UER denominators | {finding.queries} |",
        f"| paired queries with reference recall | {guard.get('paired_queries', 'n/a')} |",
        "",
        "## Why the recall guard is reported beside UER and never after it",
        "",
        "A verifier can lower UER by deleting every edge it cannot confirm. That produces a "
        "better headline number and a worse answer. H2d is the check: reference-edge recall "
        "under M must stay within 10 points of B1, or the UER improvement is not a repair. "
        f"Guard status: {guard.get('status', 'unknown')}.",
        "",
        f"Scope: {guard.get('scope', 'development guard only')}.",
        "",
        *_secondary_section(result),
        *_exploratory_section(result),
        *(
            [
                "**This run was scored with `--no-references`**, so reference-edge recall "
                "was never computed and H2d cannot be evaluated at all. RQ1 is unaffected; "
                "RQ2 is not a result until the reference graphs are signed and in scope.",
                "",
            ]
            if args.no_references
            else []
        ),
    ]
    args.rq2.write_text("\n".join(line.rstrip() for line in rq2).rstrip() + "\n", encoding="utf-8")

    print(f"wrote {args.rq1} and {args.rq2}")
    print(json.dumps({"rq2_guard": finding.recall_guard, "conditions": sorted(scores)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
