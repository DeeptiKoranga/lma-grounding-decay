"""How many corpus passages can mention each ontology variable at all (B6/#38).

    python scripts/audit_alias_coverage.py [--corpus PATH] [--report PATH]

Rule 3 of the verifier requires both variables of an edge to be named in the
cited passage, through `data/aliases.yaml`. A variable whose surface forms never
appear in the corpus therefore **cannot carry a source-asserted edge at all**,
however much the sources discuss it, and reference-edge recall is capped by that
before any model runs.

This counts, for every variable in the closed ontology, how many passages
contain at least one of its alias forms. It is a property of the corpus and the
alias table together, so it bounds what any condition can achieve and is worth
knowing before results are read rather than after.

Matching mirrors `verify.rules.check_variables_mentioned`: case-insensitive
substring over the passage text. It is therefore an upper bound on mentions, not
on asserted edges: a passage that names a variable need not say anything about
it.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from datetime import date
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
CORPUS = REPO / "data/processed/articles.jsonl"
ALIASES = REPO / "data/aliases.yaml"
ONTOLOGY = REPO / "src/schema/ontology.yaml"
REPORT = REPO / "reports/alias_coverage.md"

#: Below this many passages, a variable is effectively unevidenceable: too few
#: places where an edge touching it could be anchored for any realistic query.
THIN = 10


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus", type=Path, default=CORPUS)
    parser.add_argument("--report", type=Path, default=REPORT)
    args = parser.parse_args(argv)

    if not args.corpus.is_file():
        raise SystemExit(f"{args.corpus} not found; see data/processed/MANIFEST.md")

    ontology = yaml.safe_load(ONTOLOGY.read_text(encoding="utf-8"))["variables"]
    aliases = yaml.safe_load(ALIASES.read_text(encoding="utf-8"))["aliases"]

    folded = {
        # Longest first so the most specific form wins, then alphabetically:
        # ties broken by set order vary between runs under hash randomisation,
        # which made this generated report differ from itself.
        var: sorted({form.lower() for form in aliases.get(var, [])}, key=lambda f: (-len(f), f))
        for var in ontology
    }

    hits: Counter[str] = Counter()
    by_form: Counter[str] = Counter()
    passages = 0
    with args.corpus.open(encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            passages += 1
            text = json.loads(line)["text"].lower()
            for var, forms in folded.items():
                for form in forms:
                    if form in text:
                        hits[var] += 1
                        by_form[f"{var}\u0000{form}"] += 1
                        break

    ranked = sorted(ontology, key=lambda v: (hits[v], v))
    absent = [v for v in ranked if hits[v] == 0]
    thin = [v for v in ranked if 0 < hits[v] < THIN]
    dead_forms = {
        var: [f for f in folded[var] if by_form[f"{var}\u0000{f}"] == 0] for var in ontology
    }

    lines = [
        "# Alias coverage over the frozen corpus",
        "",
        "<!-- Generated by scripts/audit_alias_coverage.py. Do not edit by hand. -->",
        "",
        f"Run {date.today()} over **{passages:,} passages** and "
        f"**{len(ontology)} ontology variables**.",
        "",
        "Rule 3 requires both variables of an edge to be named in the cited passage, via",
        "`data/aliases.yaml`. A variable the corpus never names **cannot carry a",
        "source-asserted edge at all**, so these counts cap reference-edge recall before",
        "any model runs. They are an upper bound on *mentions*, not on asserted edges: a",
        "passage that names a variable need not say anything about it.",
        "",
        "## Headline",
        "",
        f"- **{len(absent)} of {len(ontology)}** variables are never named in the corpus.",
        f"- **{len(thin)}** more are named in fewer than {THIN} passages.",
        f"- {len(ontology) - len(absent) - len(thin)} are comfortably evidenceable.",
        "",
    ]

    if absent:
        lines += [
            "## Never named — no source-asserted edge is possible",
            "",
            "| variable | alias forms tried |",
            "|---|---|",
            *(f"| `{v}` | {', '.join(repr(f) for f in folded[v]) or '(none)'} |" for v in absent),
            "",
        ]
    if thin:
        lines += [
            f"## Named in fewer than {THIN} passages",
            "",
            "| variable | passages | forms that never match |",
            "|---|---:|---|",
            *(
                f"| `{v}` | {hits[v]} | "
                f"{', '.join(repr(f) for f in dead_forms[v]) if dead_forms[v] else '—'} |"
                for v in thin
            ),
            "",
        ]

    lines += [
        "## All variables, least covered first",
        "",
        "| variable | passages | % of corpus |",
        "|---|---:|---:|",
        *(f"| `{v}` | {hits[v]:,} | {hits[v] / passages:.2%} |" for v in ranked),
        "",
        "## What to do with this",
        "",
        "An absent or thin variable has two possible causes, and they need opposite fixes.",
        "Either the corpus genuinely does not discuss it, in which case queries targeting it",
        "cannot be answered and should be rescoped; or the sources discuss it in wording the",
        "alias table does not list, in which case the table is incomplete and extending it is",
        "a correctness fix.",
        "",
        "**Telling the two apart requires reading the corpus, not guessing.** Extending the",
        "table to make a particular gold edge pass would be fitting the instrument to the",
        "data; extending it because the corpus demonstrably uses a form the table lacks is",
        "the fix the table exists for. `data/aliases.yaml` is Track A's under D-16, so the",
        "evidence belongs in an issue rather than in an unannounced edit.",
    ]

    args.report.write_text("\n".join(line.rstrip() for line in lines) + "\n", encoding="utf-8")
    print(f"wrote {args.report.relative_to(REPO)}")
    print(f"never named: {len(absent)}  thin(<{THIN}): {len(thin)}  of {len(ontology)}")
    if absent:
        print("  absent:", ", ".join(absent))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
