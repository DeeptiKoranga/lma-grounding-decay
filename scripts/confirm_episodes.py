"""Confirm the candidate anchor episodes (B2) and write data/eval/episodes.md.

    python scripts/confirm_episodes.py [--check]

Reads `data/eval/episodes.yaml` and the series store, applies as-of discipline,
and regenerates the episode table. `--check` writes nothing and exits non-zero
if the committed document is stale, so CI can catch a series update that was
never reflected in the anchors.
"""

from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

from corpus.series import SeriesStore
from eval.episodes import Disposition, EpisodeConfirmation, confirm_episodes, load_episode_set

REPO = Path(__file__).resolve().parent.parent
EPISODES_YAML = REPO / "data/eval/episodes.yaml"
EPISODES_MD = REPO / "data/eval/episodes.md"
SERIES_ROOT = REPO / "data/series"

_HEADLINE = {
    Disposition.CONFIRMED: "usable as declared",
    Disposition.REDATE: "usable only at a later as-of date",
    Disposition.UNCONFIRMED: "not usable; drop or restate",
    Disposition.NO_SERIES: "document-confirmed only",
}


def _value(result: EpisodeConfirmation) -> str:
    if result.observed_value is None:
        return "—"
    value = result.observed_value
    text = f"{value:,.4f}".rstrip("0").rstrip(".")
    return text or "0"


def _provenance(result: EpisodeConfirmation) -> str:
    official = result.official_source
    if official is None:
        return "—"
    return "official" if official else "news-reported"


def _row(result: EpisodeConfirmation) -> str:
    cells = [
        f"`{result.episode_id}`",
        result.label,
        f"**{result.disposition.value}**",
        f"{result.observed_on or '—'}",
        _value(result),
        f"{result.available_on or '—'}",
        _provenance(result),
        f"{result.earliest_as_of or '—'}",
    ]
    return "| " + " | ".join(cells) + " |"


def render(results: list[EpisodeConfirmation], checked_on: date) -> str:
    by = {d: [r for r in results if r.disposition is d] for d in Disposition}
    confirmed = len(by[Disposition.CONFIRMED])
    official = sum(1 for r in by[Disposition.CONFIRMED] if r.official_source)

    lines = [
        "# Anchor episodes — confirmation against the series store (B2)",
        "",
        "<!-- Generated by scripts/confirm_episodes.py. Do not edit by hand; edit",
        "     data/eval/episodes.yaml and re-run. `--check` fails if this is stale. -->",
        "",
        f"Checked {checked_on}. Source of truth: `data/eval/episodes.yaml` plus the",
        "series store in `data/series/` (original-vintage files only; the October",
        "retrospective snapshot is deliberately excluded).",
        "",
        "An episode is **confirmed** only when an observation satisfying its claim had",
        "already been *published* by the episode's as-of date. An observation released",
        "later cannot confirm an earlier anchor. Series confirm that a move happened;",
        "they are never evidence for an edge (proposal section 10).",
        "",
        f"**{confirmed} of {len(results)} episodes are confirmed as declared**, of which "
        f"{official} against official data.",
        "",
        "| id | episode | disposition | observed on | value | published | provenance | earliest as-of |",
        "|---|---|---|---|---|---|---|---|",
    ]
    order = [
        Disposition.CONFIRMED,
        Disposition.REDATE,
        Disposition.UNCONFIRMED,
        Disposition.NO_SERIES,
    ]
    for disposition in order:
        for result in by[disposition]:
            lines.append(_row(result))

    lines += ["", "## What each disposition means for the query set", ""]
    for disposition in order:
        group = by[disposition]
        if not group:
            continue
        lines.append(f"### {disposition.value} — {_HEADLINE[disposition]}")
        lines.append("")
        for result in group:
            lines.append(f"- **{result.label}** (`{result.episode_id}`) — {result.reason}.")
            if result.source_url:
                lines.append(f"  Source: {result.source_url}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 if the committed document is stale",
    )
    args = parser.parse_args(argv)

    episode_set = load_episode_set(EPISODES_YAML)
    store = SeriesStore.from_directory(SERIES_ROOT)
    results = list(confirm_episodes(episode_set, store))
    rendered = render(results, episode_set.checked_on)

    if args.check:
        current = EPISODES_MD.read_text(encoding="utf-8") if EPISODES_MD.is_file() else ""
        if current != rendered:
            print(
                f"{EPISODES_MD.relative_to(REPO)} is stale; " "re-run scripts/confirm_episodes.py",
                file=sys.stderr,
            )
            return 1
        print(f"{EPISODES_MD.relative_to(REPO)} is up to date")
        return 0

    EPISODES_MD.write_text(rendered, encoding="utf-8")
    counts = ", ".join(
        f"{d.value}={sum(1 for r in results if r.disposition is d)}" for d in Disposition
    )
    print(f"wrote {EPISODES_MD.relative_to(REPO)} ({counts})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
